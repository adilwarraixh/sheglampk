/* =========================================================
   db/export-catalogue.js — database → data/products.json

   The database is the source of truth. This writes the build-time
   snapshot the static generator reads, so the pre-rendered HTML matches
   what the API serves (good for SEO and for JavaScript-off visitors).

   Products are written newest first (by when they were first published).
   Every list the shop shows — New in, Bestsellers, On sale, category
   pages — keeps this order, so a product added today leads them instead
   of queueing behind the oldest ones.

   If the database is unreachable the existing snapshot is left alone and
   the build continues — a transient database blip must not take the
   whole storefront offline.

   Run:  node db/export-catalogue.js
   ========================================================= */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "data", "products.json");

/* What the shop is built from, without writing anything — the tests read
   this to check what the homepage would show. */
async function snapshot(now = new Date()) {
  const { sql } = require("./client.js");
  const { priceOf } = require("../lib/pricing.js");
  const { isNew } = require("../lib/catalogue.js");

  const products = await sql`
    SELECT p.id, p.slug, p.sku, p.name, p.subcategory, p.short_description, p.description,
           p.finish, p.size, p.price, p.sale_price, p.sale_starts_at, p.sale_ends_at, p.stock_quantity,
           p.is_featured, p.is_bestseller, p.is_new_arrival, p.published_at, p.tags,
           p.seo_title, p.seo_description,
           c.slug AS category_slug
      FROM products p
      LEFT JOIN categories c ON c.id = p.category_id
     WHERE p.status = 'PUBLISHED'
     ORDER BY p.published_at DESC NULLS LAST, p.id DESC`;

  const ids = products.map((p) => p.id);
  const [variants, images, reviews] = await Promise.all([
    ids.length ? sql`
    SELECT product_id, id, variant_name, hex, stock_quantity, position
      FROM product_variants WHERE product_id = ANY(${ids}) AND is_available
     ORDER BY product_id, position` : [],
    ids.length ? sql`
    SELECT product_id, variant_id, url, alt, position, is_primary
      FROM product_images WHERE product_id = ANY(${ids}) ORDER BY product_id, position` : [],
    // Only reviews an admin has approved (lib/inbox.js).
    require("../lib/inbox.js").approvedReviews(),
  ]);

  const group = (rows, key = "product_id") => rows.reduce((m, r) => {
    (m[r[key]] = m[r[key]] || []).push(r); return m;
  }, {});
  const vById = group(variants), iById = group(images);

  const out = products.map((p) => {
    const imgs = iById[p.id] || [];
    const vars = vById[p.id] || [];
    const imageOf = (variantId) => (imgs.find((i) => i.variant_id === variantId) || {}).url || null;
    const pr = priceOf(p, now);

    return {
      /* The database id. The checkout sends this so the server can price
         and reserve the exact row, rather than guessing from a name. */
      dbId: Number(p.id),
      name: p.name,
      category: p.category_slug,
      sub: p.subcategory,
      // Shop fields: `price` is what the customer pays (the checkout charges
      // the same priceOf().final) and `oldPrice` the regular price it shows
      // struck through, only while a sale is on.
      price: pr.final,
      oldPrice: pr.onSale ? pr.regular : null,
      finish: p.finish,
      size: p.size,
      isNew: isNew(p, now),
      publishedAt: p.published_at ? new Date(p.published_at).toISOString() : null,
      isBestSeller: p.is_bestseller,
      isFeatured: p.is_featured,
      desc: p.description,
      shortDesc: p.short_description,
      shades: vars.length
        ? vars.map((v) => ({ id: Number(v.id), name: v.variant_name, hex: v.hex, stock: v.stock_quantity, image: imageOf(v.id) }))
        : null,
      slug: p.slug,
      sku: p.sku,
      stock: p.stock_quantity,
      tags: p.tags || [],
      seoTitle: p.seo_title,
      seoDescription: p.seo_description,
      reviews: reviews[p.slug] || [],
      // Explicit URL: images are named per product AND shade, so they can
      // no longer be found by matching a filename to the product slug.
      image: (imgs.find((i) => i.is_primary) || imgs[0] || {}).url || null,
      images: imgs.map((i) => i.url),
    };
  });

  /* The admin's Settings, for everything the shop prints: delivery charges,
     returns, contact details, the announcement bar, whether to take orders.
     data/catalog.js applies them over its defaults. */
  const s = await require("../lib/site-admin.js").shopSettings();
  const settings = {
    freeShippingOver: s.freeShippingOver, flatShipping: s.flatShipping, returnDays: s.returnDays,
    contactEmail: s.contactEmail, contactPhone: s.contactPhone, whatsapp: s.whatsapp,
    announcement: s.announcement, ordersEnabled: s.ordersEnabled,
  };

  return {
    _comment: "GENERATED by db/export-catalogue.js from the database. Edit products in the admin portal, not here.",
    version: 3,
    updated: now.toISOString(),
    settings,
    products: out,
  };
}

let mark = null;   // this build's export stamp, put back if the export fails

async function main() {
  const { sql, describeTarget } = require("./client.js");
  console.log(`\nCatalogue export ← ${describeTarget()}`);

  /* Stamped before reading, so a change saved while this export runs is not
     mistaken for one it includes (see lib/rebuild.js). Only a production
     build counts: a local or preview build does not change the live shop. */
  if (process.env.VERCEL_ENV === "production") {
    try { mark = await require("../lib/rebuild.js").markExported(); }
    catch (e) { console.warn(`  (could not record the export time: ${e.message})`); }
  }
  console.log(`  automatic rebuilds: ${process.env.DEPLOY_HOOK_URL ? "deploy hook configured" : "DEPLOY_HOOK_URL is not set"}`);

  const payload = await snapshot();
  const out = payload.products;
  fs.writeFileSync(OUT, JSON.stringify(payload, null, 1), "utf8");

  /* Hero slides come from the database too, so editing them in the portal
     changes the homepage on the next deploy rather than needing a code
     edit. Only enabled slides are written. */
  const slides = await sql`
    SELECT position, eyebrow, headline, subtext, cta_label, cta_href,
           cta2_label, cta2_href, video_url, video_mobile_url, poster_url
      FROM hero_slides WHERE is_enabled ORDER BY position, id`;
  if (slides.length) {
    const heroPath = path.join(__dirname, "..", "data", "hero.json");
    fs.writeFileSync(heroPath, JSON.stringify({
      _comment: "GENERATED by db/export-catalogue.js. Edit hero slides in the admin portal.",
      updated: new Date().toISOString(),
      slides: slides.map((s, i) => ({
        id: "slide-" + (i + 1),
        enabled: true,
        eyebrow: s.eyebrow || "",
        headline: s.headline,
        sub: s.subtext || "",
        ctaLabel: s.cta_label || "",
        ctaHref: s.cta_href || "",
        cta2Label: s.cta2_label || "",
        cta2Href: s.cta2_href || "",
        video: s.video_url || "",
        videoMobile: s.video_mobile_url || "",
        poster: s.poster_url || "",
      })),
    }, null, 1), "utf8");
    console.log(`  ${slides.length} hero slides written to data/hero.json`);
  }

  const withImages = out.filter((p) => p.image).length;
  console.log(`  ${out.length} published products written to data/products.json`);
  console.log(`  ${out.filter((p) => p.isNew).length} new, ${out.filter((p) => p.oldPrice).length} on sale`);
  console.log(`  ${withImages}/${out.length} have an image, ${out.reduce((a, p) => a + (p.shades ? p.shades.length : 0), 0)} shades\n`);
}

if (require.main === module) {
  main().catch(async (e) => {
    const existing = fs.existsSync(OUT);
    console.error(`\n! Catalogue export failed: ${e.message}`);
    if (mark) {
      try { await require("../lib/rebuild.js").unmarkExported(mark); }
      catch (err) { console.warn(`  (could not put back the export time: ${err.message})`); }
    }
    /* Postgres class 42 (no such column, table or type) is this code
       running against a database that has not been migrated — not a blip.
       Shipping it would break checkout, so the build stops and the live
       shop stays as it is. */
    if (/^42/.test(String(e.code || ""))) {
      console.error("  The database is missing something this code needs. Run the pending migration first.\n");
      process.exit(1);
    }
    if (existing) {
      console.error("  Keeping the existing data/products.json and continuing the build.\n");
      process.exit(0);           // do not break the build over a transient outage
    }
    console.error("  No previous snapshot exists, so the build cannot continue.\n");
    process.exit(1);
  });
}

module.exports = { snapshot };
