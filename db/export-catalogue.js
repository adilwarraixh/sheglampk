/* =========================================================
   db/export-catalogue.js — database → data/products.json

   The database is the source of truth. This writes the build-time
   snapshot the static generator reads, so the pre-rendered HTML matches
   what the API serves (good for SEO and for JavaScript-off visitors).

   The page ALSO refetches /api/products at runtime, so publishing a
   product shows up without a rebuild. This snapshot is the floor, not
   the ceiling.

   If the database is unreachable the existing snapshot is left alone and
   the build continues — a transient database blip must not take the
   whole storefront offline.

   Run:  node db/export-catalogue.js
   ========================================================= */
const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "data", "products.json");

async function main() {
  const { sql, describeTarget } = require("./client.js");
  console.log(`\nCatalogue export ← ${describeTarget()}`);

  const products = await sql`
    SELECT p.id, p.slug, p.sku, p.name, p.subcategory, p.short_description, p.description,
           p.finish, p.size, p.price, p.sale_price, p.stock_quantity,
           p.is_featured, p.is_bestseller, p.is_new_arrival, p.tags,
           p.seo_title, p.seo_description,
           c.slug AS category_slug
      FROM products p
      LEFT JOIN categories c ON c.id = p.category_id
     WHERE p.status = 'PUBLISHED'
     ORDER BY p.id`;

  const ids = products.map((p) => p.id);
  const variants = ids.length ? await sql`
    SELECT product_id, id, variant_name, hex, stock_quantity, position
      FROM product_variants WHERE product_id = ANY(${ids}) ORDER BY product_id, position` : [];
  const images = ids.length ? await sql`
    SELECT product_id, variant_id, url, alt, position, is_primary
      FROM product_images WHERE product_id = ANY(${ids}) ORDER BY product_id, position` : [];

  const group = (rows, key = "product_id") => rows.reduce((m, r) => {
    (m[r[key]] = m[r[key]] || []).push(r); return m;
  }, {});
  const vById = group(variants), iById = group(images);

  const out = products.map((p) => {
    const imgs = iById[p.id] || [];
    const vars = vById[p.id] || [];
    const imageOf = (variantId) => (imgs.find((i) => i.variant_id === variantId) || {}).url || null;
    const sale = p.sale_price === null ? null : Number(p.sale_price);
    const regular = p.price === null ? null : Number(p.price);

    return {
      name: p.name,
      category: p.category_slug,
      sub: p.subcategory,
      // The card shows `price` and strikes through `oldPrice`, so a sale
      // means price = the discounted one and oldPrice = the original.
      price: sale !== null ? sale : regular,
      oldPrice: sale !== null ? regular : null,
      finish: p.finish,
      size: p.size,
      isNew: p.is_new_arrival,
      isBestSeller: p.is_bestseller,
      isFeatured: p.is_featured,
      desc: p.description,
      shortDesc: p.short_description,
      shades: vars.length
        ? vars.map((v) => ({ name: v.variant_name, hex: v.hex, stock: v.stock_quantity, image: imageOf(v.id) }))
        : null,
      slug: p.slug,
      sku: p.sku,
      stock: p.stock_quantity,
      tags: p.tags || [],
      seoTitle: p.seo_title,
      seoDescription: p.seo_description,
      // Explicit URL: images are named per product AND shade, so they can
      // no longer be found by matching a filename to the product slug.
      image: (imgs.find((i) => i.is_primary) || imgs[0] || {}).url || null,
      images: imgs.map((i) => i.url),
    };
  });

  const payload = {
    _comment: "GENERATED by db/export-catalogue.js from the database. Edit products in the admin portal, not here.",
    version: 3,
    updated: new Date().toISOString(),
    products: out,
  };
  fs.writeFileSync(OUT, JSON.stringify(payload, null, 1), "utf8");

  const withImages = out.filter((p) => p.image).length;
  console.log(`  ${out.length} published products written to data/products.json`);
  console.log(`  ${withImages}/${out.length} have an image, ${out.reduce((a, p) => a + (p.shades ? p.shades.length : 0), 0)} shades\n`);
}

main().catch((e) => {
  const existing = fs.existsSync(OUT);
  console.error(`\n! Catalogue export failed: ${e.message}`);
  if (existing) {
    console.error("  Keeping the existing data/products.json and continuing the build.\n");
    process.exit(0);           // do not break the build over a transient outage
  }
  console.error("  No previous snapshot exists, so the build cannot continue.\n");
  process.exit(1);
});
